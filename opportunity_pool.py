"""
Persistent Opportunity Pool for Atlas.

Manages the lifecycle of trading opportunities from discovery to active tracking.
Three distinct pools:
1. Candidate Pool - Raw setup candidates from scanning
2. Validated Pool - Setups that passed common filter, ready for user review
3. Active Tracking Pool - User-accepted setups with position management
"""

from __future__ import annotations

import json
import logging
import math
import os
import threading
import time
from collections import defaultdict
from dataclasses import asdict, dataclass, field
from datetime import datetime
from enum import Enum
from pathlib import Path
from typing import Any, Dict, List, Optional, Set

logger = logging.getLogger("atlas.opportunity_pool")


class SetupStatus(Enum):
    """Setup lifecycle states."""
    DISCOVERED = "DISCOVERED"          # Found by scanner, pending analysis
    ANALYZING = "ANALYZING"            # Strategy analysis in progress
    CANDIDATE = "CANDIDATE"            # Raw setup generated by strategy
    VALIDATED = "VALIDATED"            # Passed common filter
    ACTIVE = "ACTIVE"                  # User-accepted, awaiting entry
    ENTRY_PENDING = "ENTRY_PENDING"    # LIMIT order waiting for fill
    ENTERED = "ENTERED"                # Position opened
    TP1 = "TP1"                        # First target hit
    TP2 = "TP2"                        # Second target hit
    TP3 = "TP3"                        # Third target hit
    INVALIDATED = "INVALIDATED"        # Setup no longer valid
    EXPIRED = "EXPIRED"                # Time-based expiry
    REJECTED = "REJECTED"              # Failed validation
    CANCELLED = "CANCELLED"            # User cancelled


class SetupType(Enum):
    """Type of setup entry."""
    MARKET = "MARKET"
    LIMIT = "LIMIT"


@dataclass
class SetupCandidate:
    """A trading setup candidate with full lifecycle tracking."""
    # Identity
    setup_id: str
    symbol: str
    strategy_id: str
    strategy_name: str
    
    # Core setup data
    direction: str  # LONG/SHORT
    entry_type: str  # MARKET/LIMIT
    entry_price: float
    stop_loss: float
    tp1: float
    tp2: float
    tp3: float
    
    # Risk metrics
    rr_tp1: float
    rr_tp2: float
    rr_tp3: float
    net_rr: float
    risk_reward: float
    
    # Quality
    confidence: float
    grade: str
    score: float
    net_rr_after_costs: float
    
    # Metadata
    status: str = SetupStatus.DISCOVERED.value
    setup_type: str = SetupType.LIMIT.value
    regime: str = "UNKNOWN"
    market_phase: str = "UNKNOWN"
    
    # Reasoning
    reasons: List[str] = field(default_factory=list)
    supporting_evidence: List[str] = field(default_factory=list)
    opposing_evidence: List[str] = field(default_factory=list)
    
    # Lifecycle timestamps (ms since epoch)
    created_at_ms: int = 0
    updated_at_ms: int = 0
    validated_at_ms: int = 0
    accepted_at_ms: int = 0
    entered_at_ms: int = 0
    closed_at_ms: int = 0
    
    # Source data reference
    trace_id: Optional[str] = None
    data_snapshot_id: Optional[str] = None
    
    # User interaction
    user_accepted: bool = False
    user_id: Optional[str] = None
    telegram_message_id: Optional[int] = None
    
    # Position tracking (for active setups)
    position_size: float = 0.0
    entry_filled_price: Optional[float] = None
    current_tp: int = 0  # 0=none, 1=TP1, 2=TP2, 3=TP3
    trailing_stop: Optional[float] = None
    unrealized_pnl_r: float = 0.0
    close_price: Optional[float] = None
    
    # Expiry
    expires_at_ms: Optional[int] = None
    invalidation_reason: Optional[str] = None
    
    def to_dict(self) -> Dict[str, Any]:
        d = asdict(self)
        # Convert enums to strings
        d["status"] = self.status
        return d
    
    @classmethod
    def from_dict(cls, data: Dict[str, Any]) -> "SetupCandidate":
        # Handle old format compatibility
        if "entry" in data and "entry_price" not in data:
            data["entry_price"] = data.pop("entry")
        if "sl" in data and "stop_loss" not in data:
            data["stop_loss"] = data.pop("sl")
        
        # Filter known fields
        known = {f.name: f for f in cls.__dataclass_fields__.values()}
        filtered = {k: v for k, v in data.items() if k in known}
        # Sanitize types so a corrupted or hand-edited JSON file can never
        # poison the pool with a malformed record.
        for name, fdef in known.items():
            if name not in filtered:
                continue
            value = filtered[name]
            try:
                if fdef.type == "float":
                    filtered[name] = None if value is None else float(value)
                elif fdef.type == "int":
                    filtered[name] = None if value is None else int(value)
                elif fdef.type == "str":
                    filtered[name] = None if value is None else str(value)
                elif fdef.type == "bool":
                    filtered[name] = bool(value)
                elif fdef.type in ("List[str]", "List[Any]") and not isinstance(value, list):
                    filtered[name] = []
            except (TypeError, ValueError, OverflowError):
                logger.warning(f"Dropped candidate record with invalid field {name}")
                return None
        required = ("setup_id", "symbol", "direction")
        if any(not str(filtered.get(name) or "").strip() for name in required):
            logger.warning(f"Dropped malformed candidate record: {data.get('setup_id')}")
            return None
        try:
            return cls(**filtered)
        except TypeError as exc:
            # Missing required geometry fields: never fabricate prices.
            logger.warning(f"Dropped incomplete candidate record {data.get('setup_id')}: {exc}")
            return None


class OpportunityPool:
    """
    Persistent pool management for trading opportunities.
    
    Three pools:
    1. Candidate Pool - All discovered setups (raw + validated)
    2. Validated Pool - Ready for user review/acceptance
    3. Active Pool - User-accepted setups with position management
    
    Features:
    - SQLite persistence with atomic writes
    - Automatic state transitions
    - Deduplication by fingerprint
    - Expiry management
    - Telegram integration hooks
    """
    
    # State file names
    CANDIDATE_DB = "candidates.json"
    VALIDATED_DB = "validated.json"
    ACTIVE_DB = "active.json"
    HISTORY_DB = "history.json"
    
    # Terminal statuses: once reached, a setup leaves the active pool and is
    # archived (never silently dropped).
    CLOSED_STATUSES = frozenset({
        SetupStatus.INVALIDATED.value,
        SetupStatus.EXPIRED.value,
        SetupStatus.CANCELLED.value,
        SetupStatus.TP3.value,
    })
    
    def __init__(
        self,
        base_path: str = "opportunity_pool",
        max_candidates: int = 500,
        max_validated: int = 200,
        max_history: int = 5000,
        expiry_hours: int = 24,
        freshness_hours: int = 2,
        auto_persist: bool = True,
        persist_interval: int = 30,
    ):
        self.base_path = Path(base_path)
        self.base_path.mkdir(parents=True, exist_ok=True)
        
        self.max_candidates = max_candidates
        self.max_validated = max_validated
        self.max_history = max_history
        self.expiry_hours = expiry_hours
        self.freshness_hours = max(1, int(freshness_hours))
        
        self._lock = threading.RLock()
        
        # In-memory pools
        self._candidates: Dict[str, SetupCandidate] = {}      # All candidates
        self._validated: Dict[str, SetupCandidate] = {}       # Validated, ready for user
        self._active: Dict[str, SetupCandidate] = {}          # User-accepted
        self._history: List[Dict[str, Any]] = []              # Closed setups
        self._history_flushed = 0                             # Rows already in SQLite
        
        # Indexes
        self._by_symbol: Dict[str, Set[str]] = defaultdict(set)
        self._by_strategy: Dict[str, Set[str]] = defaultdict(set)
        self._by_status: Dict[str, Set[str]] = defaultdict(set)
        
        # SQLite persistence (primary store; JSON files stay as a mirror)
        from pool_store import PoolStore
        self._store: Optional[PoolStore] = PoolStore(str(self.base_path))
        
        # Persistence
        self.auto_persist = bool(auto_persist)
        self.persist_interval = max(1, int(persist_interval))
        self._persist_thread: Optional[threading.Thread] = None
        self._stop_persist = threading.Event()
        
        # Load persisted state
        self.load_all()
        
        # Start persistence thread only when auto persistence is enabled
        self._running = True
        if self.auto_persist:
            self._persist_thread = threading.Thread(
                target=self._persist_loop,
                daemon=True,
                name="OpportunityPoolPersist"
            )
            self._persist_thread.start()
        
        logger.info(f"OpportunityPool initialized: "
                   f"{len(self._candidates)} candidates, "
                   f"{len(self._validated)} validated, "
                   f"{len(self._active)} active, "
                   f"auto_persist={self.auto_persist}, "
                   f"persist_interval={self.persist_interval}s")
    
    def _persist_loop(self):
        """Background persistence loop honoring auto_persist/persist_interval."""
        while not self._stop_persist.wait(self.persist_interval):
            try:
                self.save_all()
            except Exception as e:
                logger.error(f"OpportunityPool persistence failed: {e}")

    # ---------------------------------------------------------------------
    # Candidate Pool (Discovered setups)
    # ---------------------------------------------------------------------
    
    def add_candidate(self, candidate: SetupCandidate) -> bool:
        """
        Add a new candidate to the pool.
        
        Returns True if added, False if duplicate or pool full.
        Deduplication uses symbol + direction + strategy_id fingerprint.
        """
        with self._lock:
            # A new analysis supersedes only an older unaccepted setup from
            # the same strategy. Other strategies remain independent and are
            # removed only when their own generator reports broken structure.
            symbol_ids = list(self._by_symbol.get(candidate.symbol, set()))
            same_id = None
            for existing_id in symbol_ids:
                existing = self._candidates.get(existing_id) or self._validated.get(existing_id)
                if existing is None:
                    continue
                if existing_id == candidate.setup_id:
                    same_id = existing
                    continue
                # A new setup replaces only the previous setup from the SAME
                # strategy. Independent strategies keep their own live setup
                # until their own generator reports that its structure failed.
                if existing.strategy_id != candidate.strategy_id:
                    continue
                self._remove_candidate(existing_id)
                self._remove_validated(existing_id)
                self._archive_candidate(
                    existing,
                    SetupStatus.INVALIDATED.value,
                    "REPLACED_BY_NEW_ANALYSIS",
                )
                logger.info(
                    "Strategy setup superseded | symbol=%s strategy=%s old=%s new=%s",
                    candidate.symbol, candidate.strategy_id, existing_id, candidate.setup_id,
                )

            if same_id is not None:
                # Same geometry/identity: refresh the existing record instead
                # of creating a duplicate or resetting its original creation time.
                self._update_candidate(same_id, candidate)
                same_id.updated_at_ms = int(time.time() * 1000)
                self.save_all()
                return False

            # Check capacity - evict expired first, then oldest if needed
            if len(self._candidates) >= self.max_candidates:
                self._evict_oldest_candidate()
            
            # Add new candidate. The runtime produces a deterministic
            # created_at_ms for freshness; only stamp it when missing so
            # setup age is never fabricated.
            now_ms = int(time.time() * 1000)
            if not candidate.created_at_ms:
                candidate.created_at_ms = now_ms
            if not candidate.updated_at_ms:
                candidate.updated_at_ms = candidate.created_at_ms
            if not candidate.expires_at_ms:
                candidate.expires_at_ms = candidate.created_at_ms + (
                    self.expiry_hours * 3600 * 1000
                )
            
            self._candidates[candidate.setup_id] = candidate
            self._index_candidate(candidate)
            
            # Persist the replacement, validated state and superseded history
            # together; a restart must never resurrect the previous setup.
            self.save_all()
            
            logger.info(f"New candidate added: {candidate.setup_id} "
                       f"({candidate.symbol} {candidate.direction} "
                       f"{candidate.strategy_id})")
            return True
    
    def _find_duplicate(self, candidate: SetupCandidate) -> Optional[str]:
        """Find existing setup with same symbol, direction, and strategy fingerprint.

        Searches every live pool (candidates, validated, active) so a setup
        that already advanced to another pool is never re-added as a duplicate.
        """
        pools = (self._candidates, self._validated, self._active)
        for pool in pools:
            for cid in self._by_symbol.get(candidate.symbol, set()):
                existing = pool.get(cid)
                if not existing:
                    continue
                # Exact match: same direction and strategy
                if existing.direction == candidate.direction and existing.strategy_id == candidate.strategy_id:
                    return cid
        return None
    
    def _update_candidate(self, existing: SetupCandidate, new: SetupCandidate):
        """Update existing candidate with newer data."""
        existing.updated_at_ms = int(time.time() * 1000)
        existing.entry_price = new.entry_price
        existing.stop_loss = new.stop_loss
        existing.tp1 = new.tp1
        existing.tp2 = new.tp2
        existing.tp3 = new.tp3
        existing.rr_tp1 = new.rr_tp1
        existing.rr_tp2 = new.rr_tp2
        existing.rr_tp3 = new.rr_tp3
        existing.net_rr = new.net_rr
        existing.risk_reward = new.risk_reward
        existing.confidence = new.confidence
        existing.grade = new.grade
        existing.score = new.score
        existing.net_rr_after_costs = new.net_rr_after_costs
        existing.reasons = new.reasons
        existing.supporting_evidence = new.supporting_evidence
        existing.opposing_evidence = new.opposing_evidence
        existing.trace_id = new.trace_id
        existing.data_snapshot_id = new.data_snapshot_id
    
    def _evict_oldest_candidate(self):
        """Remove oldest expired candidate to make room; fall back to oldest by creation time."""
        now = int(time.time() * 1000)
        if not self._candidates:
            return
        # First try to remove expired candidates
        expired = [
            (cid, c.created_at_ms) for cid, c in self._candidates.items()
            if c.expires_at_ms and c.expires_at_ms < now
        ]
        if expired:
            oldest = min(expired, key=lambda x: x[1])
            self._evict_candidate(oldest[0])
            return
        # No expired candidates - remove oldest by creation time
        oldest = min(self._candidates.items(), key=lambda x: x[1].created_at_ms)
        self._evict_candidate(oldest[0])

    def _evict_candidate(self, setup_id: str):
        """Evict a candidate: archive first so capacity pressure never loses setups."""
        candidate = self._candidates.get(setup_id)
        if not candidate:
            return
        # Unindex while the original status is intact, then archive; otherwise
        # the old status bucket would keep a stale id.
        self._remove_candidate(setup_id)
        self._archive_candidate(candidate, SetupStatus.EXPIRED.value, "EVICTED_CAPACITY")
    
    def _remove_candidate(self, setup_id: str):
        """Remove candidate from all indexes."""
        candidate = self._candidates.pop(setup_id, None)
        if candidate:
            self._unindex_candidate(candidate)
    
    def _index_candidate(self, candidate: SetupCandidate):
        self._by_symbol[candidate.symbol].add(candidate.setup_id)
        self._by_strategy[candidate.strategy_id].add(candidate.setup_id)
        self._by_status[candidate.status].add(candidate.setup_id)
    
    def _unindex_candidate(self, candidate: SetupCandidate):
        self._by_symbol[candidate.symbol].discard(candidate.setup_id)
        self._by_strategy[candidate.strategy_id].discard(candidate.setup_id)
        self._by_status[candidate.status].discard(candidate.setup_id)
        # Prune empty sets so per-symbol/strategy/status maps never grow
        # without bound over long-running scans.
        self._prune_index(self._by_symbol, candidate.symbol)
        self._prune_index(self._by_strategy, candidate.strategy_id)
        self._prune_index(self._by_status, candidate.status)
    
    @staticmethod
    def _prune_index(index: Dict[str, Set[str]], key: str):
        bucket = index.get(key)
        if bucket is not None and not bucket:
            index.pop(key, None)
    
    # ---------------------------------------------------------------------
    # Validated Pool (Ready for user)
    # ---------------------------------------------------------------------
    
    def validate_candidate(self, setup_id: str, trace_id: Optional[str] = None) -> bool:
        """Move candidate to validated pool after passing common filter."""
        with self._lock:
            candidate = self._candidates.pop(setup_id, None)
            if not candidate:
                return False
            
            self._unindex_candidate(candidate)
            
            candidate.status = SetupStatus.VALIDATED.value
            candidate.validated_at_ms = int(time.time() * 1000)
            candidate.updated_at_ms = int(time.time() * 1000)
            if trace_id:
                candidate.trace_id = trace_id
            
            self._validated[candidate.setup_id] = candidate
            self._index_candidate(candidate)
            
            # Enforce capacity
            if len(self._validated) > self.max_validated:
                self._evict_oldest_validated()
            
            logger.info(f"Candidate validated: {setup_id}")
            return True
    
    def _evict_oldest_validated(self):
        oldest = min(self._validated.items(), key=lambda x: x[1].validated_at_ms)
        candidate = self._validated.get(oldest[0])
        if not candidate:
            return
        self._remove_validated(oldest[0])
        self._archive_candidate(candidate, SetupStatus.EXPIRED.value, "EVICTED_CAPACITY")
    
    def _remove_validated(self, setup_id: str):
        candidate = self._validated.pop(setup_id, None)
        if candidate:
            self._unindex_candidate(candidate)
    
    def invalidate_setup(self, setup_id: str, reason: str) -> bool:
        """Invalidate a setup in any live pool and archive the removal reason.

        Archived setup IDs are deliberately not treated as symbol/strategy
        bans: a later analysis may discover and add the same setup again.
        """
        reason = str(reason or "STRUCTURE_INVALIDATED").strip()
        with self._lock:
            candidate = self._candidates.pop(setup_id, None)
            if candidate is not None:
                self._unindex_candidate(candidate)
            if candidate is None:
                candidate = self._validated.pop(setup_id, None)
                if candidate is not None:
                    self._unindex_candidate(candidate)
            if candidate is None:
                candidate = self._active.pop(setup_id, None)
                if candidate is not None:
                    self._unindex_candidate(candidate)
            if candidate is None:
                return False

            candidate.updated_at_ms = int(time.time() * 1000)
            self._archive_candidate(
                candidate, SetupStatus.INVALIDATED.value, reason
            )
            # Persist removal and history immediately; the next scan must not
            # see the invalidated record as a live duplicate after a restart.
            if self._store is not None:
                try:
                    self.save_all()
                except Exception as exc:
                    logger.error("Failed to persist invalidated setup %s: %s", setup_id, exc)
            logger.info(
                "Setup invalidated and archived | setup_id=%s symbol=%s reason=%s",
                setup_id, candidate.symbol, reason,
            )
            return True

    def reject_candidate(self, setup_id: str, reason: str) -> bool:
        """Reject and remove a candidate."""
        with self._lock:
            candidate = self._candidates.pop(setup_id, None)
            if candidate:
                self._unindex_candidate(candidate)
                self._archive_candidate(candidate, SetupStatus.REJECTED.value, reason)
                return True
            # Also check validated pool
            candidate = self._validated.pop(setup_id, None)
            if candidate:
                self._unindex_candidate(candidate)
                self._archive_candidate(candidate, SetupStatus.REJECTED.value, reason)
                return True
        return False
    
    def invalidate_strategy_setup(
        self, symbol: str, strategy_id: str, reason: str = "STRATEGY_STRUCTURE_BROKEN"
    ) -> List[SetupCandidate]:
        """Archive live, not-yet-entered setups when their own strategy breaks.

        Candidate and validated records are always eligible. User-accepted
        ACTIVE records are also removed before entry; ENTERED/TP records are
        deliberately preserved because they represent position management.
        Missing data, insufficient history and generator errors must never
        call this method.
        """
        removed: List[SetupCandidate] = []
        with self._lock:
            pools = (self._candidates, self._validated, self._active)
            for pool in pools:
                for setup_id, candidate in list(pool.items()):
                    if candidate.symbol != symbol or candidate.strategy_id != strategy_id:
                        continue
                    if pool is self._active and candidate.status != SetupStatus.ACTIVE.value:
                        continue
                    pool.pop(setup_id, None)
                    self._unindex_candidate(candidate)
                    candidate.updated_at_ms = int(time.time() * 1000)
                    self._archive_candidate(
                        candidate, SetupStatus.INVALIDATED.value, reason
                    )
                    removed.append(candidate)
            if removed:
                self.save_all()
                logger.info(
                    "Strategy setup invalidated | symbol=%s strategy=%s count=%s reason=%s",
                    symbol, strategy_id, len(removed), reason,
                )
        return removed

    def get_validated_setups(
        self,
        symbol: Optional[str] = None,
        strategy: Optional[str] = None,
        direction: Optional[str] = None,
        min_rr: float = 0.0,
        min_confidence: float = 0.0,
        limit: int = 50
    ) -> List[SetupCandidate]:
        """Get validated setups with optional filters."""
        with self._lock:
            candidates = list(self._validated.values())
            
            if symbol:
                candidates = [c for c in candidates if c.symbol == symbol]
            if strategy:
                candidates = [c for c in candidates if c.strategy_id == strategy]
            if direction:
                candidates = [c for c in candidates if c.direction == direction]
            if min_rr > 0:
                candidates = [c for c in candidates if c.net_rr >= min_rr]
            if min_confidence > 0:
                candidates = [c for c in candidates if c.confidence >= min_confidence]
            
            # Sort by net RR desc, then confidence desc
            candidates.sort(key=lambda c: (c.net_rr_after_costs, c.confidence), reverse=True)
            return candidates[:limit]
    
    def get_best_setups(self, limit: int = 5, rank: str = "composite") -> List[SetupCandidate]:
        """Read-only ranking of the validated pool.

        rank="composite" (default) uses a transparent heuristic score built
        ONLY from stored, evidence-backed fields — this is a ranking score,
        never a win probability:
          - net RR after costs (dominant, already cost-adjusted)
          - decision-engine strength (confidence)
          - mid-target richness (rr_tp2), TP structure is monotonic by design
          - setup age penalty (older setups carry staler market data)
        rank="net_rr" keeps the simple cost-adjusted RR ordering.

        Strategy-native invalidation is handled when a fresh analysis reports
        NO_SETUP or CONDITION_NOT_MET for that same strategy. Setup age and
        timestamps are not invalidation criteria. RR must still be finite and
        strictly positive before a setup is ranked.
        """
        self.cleanup_expired()
        with self._lock:
            now_ms = int(time.time() * 1000)  # Used only for ranking preference, never expiry.
            # Strategy structure, not elapsed time, determines setup validity.
            # Historical timestamps remain useful for display/audit only.
            candidates = []
            for c in self._validated.values():
                if c.status != SetupStatus.VALIDATED.value:
                    continue
                # RR validity (finite and strictly positive)
                try:
                    net_rr = float(c.net_rr_after_costs)
                except (TypeError, ValueError, OverflowError):
                    continue
                if not math.isfinite(net_rr) or net_rr <= 0:
                    continue
                candidates.append(c)
            if rank == "composite":
                def composite(c: SetupCandidate) -> float:
                    net_rr = min(float(c.net_rr_after_costs or 0.0), 6.0)
                    rr_component = net_rr / 6.0
                    confidence_component = max(0.0, min(float(c.confidence or 0.0), 100.0)) / 100.0
                    mid_target = min(max(float(c.rr_tp2 or 0.0), 0.0), 6.0) / 6.0
                    age_hours = 0.0
                    if c.created_at_ms:
                        age_hours = max(0.0, (now_ms - c.created_at_ms) / 3_600_000.0)
                    age_component = 2.718281828 ** (-age_hours / 48.0)
                    return (
                        0.45 * rr_component
                        + 0.20 * confidence_component
                        + 0.15 * mid_target
                        + 0.20 * age_component
                    )
                candidates.sort(key=composite, reverse=True)
            else:
                # Sort by net RR after costs desc, then confidence desc, then RR desc
                candidates.sort(key=lambda c: (c.net_rr_after_costs or 0, c.confidence or 0, c.net_rr or 0), reverse=True)
            return candidates[:limit]
    
    # ---------------------------------------------------------------------
    # Active Pool (User-accepted setups)
    # ---------------------------------------------------------------------
    
    def accept_setup(self, setup_id: str, user_id: str, message_id: Optional[int] = None) -> bool:
        """Move validated setup to active tracking pool (user accepted)."""
        with self._lock:
            candidate = self._validated.pop(setup_id, None)
            if not candidate:
                return False
            
            self._unindex_candidate(candidate)
            
            candidate.status = SetupStatus.ACTIVE.value
            candidate.accepted_at_ms = int(time.time() * 1000)
            candidate.updated_at_ms = int(time.time() * 1000)
            candidate.user_accepted = True
            candidate.user_id = user_id
            candidate.telegram_message_id = message_id
            
            self._active[candidate.setup_id] = candidate
            self._index_candidate(candidate)
            
            logger.info(f"Setup accepted by user {user_id}: {setup_id}")
            return True
    
    def reject_setup(self, setup_id: str) -> bool:
        """User rejected a validated setup."""
        with self._lock:
            candidate = self._validated.pop(setup_id, None)
            if candidate:
                self._unindex_candidate(candidate)
                self._archive_candidate(candidate, SetupStatus.REJECTED.value, "User rejected")
                return True
        return False
    
    def update_active_setup(
        self,
        setup_id: str,
        status: Optional[str] = None,
        entry_filled_price: Optional[float] = None,
        position_size: Optional[float] = None,
        current_tp: Optional[int] = None,
        trailing_stop: Optional[float] = None,
        unrealized_pnl_r: Optional[float] = None,
    ) -> bool:
        """Update active setup state (entry fill, TP hit, trailing stop, etc.)."""
        with self._lock:
            candidate = self._active.get(setup_id)
            if not candidate:
                return False
            
            if status:
                old_status = candidate.status
                candidate.status = status
                self._by_status[old_status].discard(setup_id)
                self._by_status[status].add(setup_id)
                self._prune_index(self._by_status, old_status)
                
                if status == SetupStatus.ENTERED.value:
                    candidate.entered_at_ms = int(time.time() * 1000)
                elif status in (SetupStatus.TP1.value, SetupStatus.TP2.value, SetupStatus.TP3.value):
                    candidate.current_tp = int(status[-1]) if status[-1].isdigit() else 0
                elif status in self.CLOSED_STATUSES:
                    # Terminal status: archive and leave the active pool; never
                    # keep a closed setup actionable in memory.
                    candidate.closed_at_ms = int(time.time() * 1000)
                    self._archive_candidate(candidate, status, "Closed via update_active_setup")
                    self._active.pop(setup_id, None)
                    self._unindex_candidate(candidate)
                    return True
            
            if entry_filled_price is not None:
                # Record the real fill without rewriting the planned entry
                # type; the original MARKET/LIMIT decision must stay intact.
                candidate.entry_filled_price = entry_filled_price
            
            if position_size is not None:
                candidate.position_size = position_size
            
            if current_tp is not None:
                candidate.current_tp = current_tp
            
            if trailing_stop is not None:
                candidate.trailing_stop = trailing_stop
            
            if unrealized_pnl_r is not None:
                candidate.unrealized_pnl_r = unrealized_pnl_r
            
            candidate.updated_at_ms = int(time.time() * 1000)
            return True
    
    def close_active_setup(self, setup_id: str, close_reason: str, close_price: float) -> bool:
        """Close an active setup and move to history.

        Only validated terminal reasons are accepted so arbitrary strings can
        never corrupt the lifecycle; close_price is preserved on the record.
        """
        with self._lock:
            candidate = self._active.get(setup_id)
            if not candidate:
                return False
            reason = str(close_reason or "").upper()
            if reason not in self.CLOSED_STATUSES:
                logger.warning(
                    f"Rejected invalid close reason for {setup_id}: {close_reason!r}"
                )
                return False
            try:
                candidate.close_price = float(close_price)
            except (TypeError, ValueError, OverflowError):
                candidate.close_price = None
            
            self._active.pop(setup_id, None)
            self._unindex_candidate(candidate)
            
            candidate.closed_at_ms = int(time.time() * 1000)
            candidate.updated_at_ms = candidate.closed_at_ms
            
            self._archive_candidate(candidate, reason, reason)
            return True
    
    def get_active_setups(self, user_id: Optional[str] = None) -> List[SetupCandidate]:
        """Get all active setups, optionally filtered by user."""
        with self._lock:
            if user_id:
                return [c for c in self._active.values() if c.user_id == user_id]
            return list(self._active.values())
    
    def get_setup(self, setup_id: str) -> Optional[SetupCandidate]:
        """Get setup by ID from any pool."""
        with self._lock:
            return (self._candidates.get(setup_id) or
                   self._validated.get(setup_id) or
                   self._active.get(setup_id))
    
    def get_all_setups(self) -> Dict[str, List[SetupCandidate]]:
        """Get all setups organized by pool."""
        with self._lock:
            return {
                "candidates": list(self._candidates.values()),
                "validated": list(self._validated.values()),
                "active": list(self._active.values()),
            }
    
    # ---------------------------------------------------------------------
    # Expiry & Cleanup
    # ---------------------------------------------------------------------
    
    def cleanup_expired(self) -> Dict[str, int]:
        """Expire raw candidates and active records; validated setups require structural invalidation."""
        now = int(time.time() * 1000)
        with self._lock:
            stats = {"candidates": 0, "validated": 0, "active": 0}
            
            # Expire candidates
            for cid, candidate in list(self._candidates.items()):
                if candidate.expires_at_ms and candidate.expires_at_ms < now:
                    self._remove_candidate(cid)
                    self._archive_candidate(candidate, SetupStatus.EXPIRED.value, "Expired")
                    stats["candidates"] += 1
            
            # Validated setups are NOT removed by age. They remain available
            # until their strategy-native structure is explicitly invalidated,
            # replaced by a newer setup from that same strategy, or user action.
            # Check active for SL/TP expiry
            for cid, candidate in list(self._active.items()):
                if candidate.expires_at_ms and candidate.expires_at_ms < now:
                    self._archive_candidate(candidate, SetupStatus.EXPIRED.value, "Expired")
                    self._active.pop(cid, None)
                    self._unindex_candidate(candidate)
                    stats["active"] += 1
            
            if any(stats.values()):
                self.save_all()
            return stats
    
    def _archive_candidate(
        self,
        candidate: SetupCandidate,
        final_status: str,
        reason: Optional[str] = None
    ):
        """Move closed/expired setup to history."""
        candidate.status = final_status
        candidate.closed_at_ms = int(time.time() * 1000)
        candidate.invalidation_reason = reason
        
        self._history.append(candidate.to_dict())
        
        # Trim history
        if len(self._history) > self.max_history:
            self._history = self._history[-self.max_history:]
    
    # ---------------------------------------------------------------------
    # Persistence
    # ---------------------------------------------------------------------
    
    def save_all(self):
        """Save all pools: SQLite (transactional primary) + JSON mirror."""
        with self._lock:
            self.base_path.mkdir(parents=True, exist_ok=True)
            
            if self._store is not None:
                try:
                    self._store.save_pool(
                        "candidates",
                        {k: v.to_dict() for k, v in self._candidates.items()},
                    )
                    self._store.save_pool(
                        "validated",
                        {k: v.to_dict() for k, v in self._validated.items()},
                    )
                    self._store.save_pool(
                        "active",
                        {k: v.to_dict() for k, v in self._active.items()},
                    )
                    new_history = self._history[self._history_flushed:]
                    if new_history:
                        inserted = self._store.append_history(new_history)
                        self._history_flushed += len(new_history)
                        if inserted < len(new_history):
                            # Duplicates were already stored; keep the counter
                            # aligned with what actually exists.
                            self._history_flushed -= (len(new_history) - inserted)
                except Exception as e:
                    logger.error(f"SQLite pool persistence failed: {e}")
            
            # JSON mirror: best effort, kept for tooling and rollback safety
            try:
                self._save_json(self.CANDIDATE_DB, {
                    "version": 1,
                    "updated_at": int(time.time() * 1000),
                    "candidates": {k: v.to_dict() for k, v in self._candidates.items()}
                })
                self._save_json(self.VALIDATED_DB, {
                    "version": 1,
                    "updated_at": int(time.time() * 1000),
                    "validated": {k: v.to_dict() for k, v in self._validated.items()}
                })
                self._save_json(self.ACTIVE_DB, {
                    "version": 1,
                    "updated_at": int(time.time() * 1000),
                    "active": {k: v.to_dict() for k, v in self._active.items()}
                })
                self._save_json(self.HISTORY_DB, {
                    "version": 1,
                    "updated_at": int(time.time() * 1000),
                    "history": self._history
                })
            except Exception as e:
                logger.error(f"JSON pool mirror failed: {e}")
    
    def _save_json(self, filename: str, data: Dict[str, Any]):
        path = self.base_path / filename
        tmp_path = path.with_name(f".{path.stem}.{os.getpid()}.tmp")
        with tmp_path.open("w", encoding="utf-8") as f:
            json.dump(data, f, ensure_ascii=False, separators=(",", ":"))
        os.replace(tmp_path, path)
    
    def load_all(self):
        """Load all pools from SQLite (primary) or migrate from legacy JSON."""
        try:
            if self._store is not None:
                stored_candidates = self._store.load_pool("candidates")
                stored_validated = self._store.load_pool("validated")
                stored_active = self._store.load_pool("active")
                stored_history = self._store.load_history()
                total_stored = (
                    len(stored_candidates) + len(stored_validated) + len(stored_active)
                )
                
                # First run on a legacy directory: import the JSON files once.
                # INSERT OR IGNORE makes this idempotent across restarts.
                if total_stored == 0 and not self._store.json_migration_done():
                    migrated = self._store.migrate_from_json(self.base_path)
                    if any(migrated.values()):
                        logger.info(
                            f"Migrated legacy JSON pools to SQLite: {migrated}"
                        )
                    self._store.mark_json_migration_done()
                    stored_candidates = self._store.load_pool("candidates")
                    stored_validated = self._store.load_pool("validated")
                    stored_active = self._store.load_pool("active")
                    stored_history = self._store.load_history()
                
                for setup_id, payload in stored_candidates.items():
                    record = SetupCandidate.from_dict(payload)
                    if record is not None:
                        self._candidates[setup_id] = record
                for setup_id, payload in stored_validated.items():
                    record = SetupCandidate.from_dict(payload)
                    if record is not None:
                        self._validated[setup_id] = record
                for setup_id, payload in stored_active.items():
                    record = SetupCandidate.from_dict(payload)
                    if record is not None:
                        self._active[setup_id] = record
                self._history = stored_history
                if len(self._history) > self.max_history:
                    self._history = self._history[-self.max_history:]
                self._history_flushed = len(self._history)
            else:
                # No SQLite store: fall back to the legacy JSON files.
                self._load_json(self.CANDIDATE_DB, "candidates", self._candidates)
                self._load_json(self.VALIDATED_DB, "validated", self._validated)
                self._load_json(self.ACTIVE_DB, "active", self._active)
                self._load_history()
            
            # Rebuild indexes
            self._rebuild_indexes()
            
            logger.info(f"Loaded pools: "
                       f"{len(self._candidates)} candidates, "
                       f"{len(self._validated)} validated, "
                       f"{len(self._active)} active, "
                       f"{len(self._history)} history")
        except Exception as e:
            logger.error(f"Failed to load opportunity pools: {e}")
    
    def _load_json(self, filename: str, key: str, target: Dict[str, SetupCandidate]):
        path = self.base_path / filename
        if not path.exists():
            return
        try:
            with path.open("r", encoding="utf-8") as f:
                data = json.load(f)
            for k, v in data.get(key, {}).items():
                record = SetupCandidate.from_dict(v)
                if record is None:
                    continue
                target[k] = record
        except Exception as e:
            logger.error(f"Failed to load {filename}: {e}")
    
    def _load_history(self):
        path = self.base_path / self.HISTORY_DB
        if not path.exists():
            return
        try:
            with path.open("r", encoding="utf-8") as f:
                data = json.load(f)
            self._history = data.get("history", [])
            # Trim if too large
            if len(self._history) > self.max_history:
                self._history = self._history[-self.max_history:]
        except Exception as e:
            logger.error(f"Failed to load history: {e}")
    
    def _rebuild_indexes(self):
        self._by_symbol.clear()
        self._by_strategy.clear()
        self._by_status.clear()
        
        for pool in [self._candidates, self._validated, self._active]:
            for candidate in pool.values():
                self._index_candidate(candidate)
    
    def archive_and_reset_scan_pools(self, day_tag: str) -> Dict[str, int]:
        """Daily refresh (requirement K): archive the previous day's pools.

        Candidates and validated setups are archived with a DAILY_REFRESH
        reason (never silently deleted), a consistent SQLite backup is
        written to the archive directory, then the two live pools are
        cleared for the new day. Active (user-accepted) setups are kept.

        If the archive backup fails, the live pools are NOT cleared so that
        a retry can attempt archiving again without data loss.
        """
        with self._lock:
            counts = {"candidates": len(self._candidates), "validated": len(self._validated)}
            archived_dir = self.base_path / "archive" / day_tag
            if self._store is not None:
                try:
                    archived_dir.mkdir(parents=True, exist_ok=True)
                    self._store.backup(archived_dir / "pool_state.db")
                except Exception as e:
                    logger.error(f"Daily archive backup failed: live pools NOT cleared: {e}")
                    raise  # Do not clear live pools; caller will not mark day done

            reason = f"DAILY_REFRESH:{day_tag}"
            for candidate in list(self._candidates.values()):
                self._remove_candidate(candidate.setup_id)
                self._archive_candidate(candidate, SetupStatus.EXPIRED.value, reason)
            for candidate in list(self._validated.values()):
                self._remove_validated(candidate.setup_id)
                self._archive_candidate(candidate, SetupStatus.EXPIRED.value, reason)
            self._history_flushed = 0  # archive rows are re-appended on save
            self.save_all()
            return counts

    def get_stats(self) -> Dict[str, Any]:
        """Get pool statistics."""
        with self._lock:
            return {
                "candidates": len(self._candidates),
                "validated": len(self._validated),
                "active": len(self._active),
                "history": len(self._history),
                "by_symbol": {s: len(ids) for s, ids in self._by_symbol.items()},
                "by_strategy": {s: len(ids) for s, ids in self._by_strategy.items()},
                "by_status": {s: len(ids) for s, ids in self._by_status.items()},
            }
    
    def get_recent_history(self, limit: int = 100) -> List[Dict[str, Any]]:
        """Get recent closed setups."""
        with self._lock:
            return self._history[-limit:]
    
    def stop(self):
        """Stop persistence, flush state and close the SQLite store."""
        self._running = False
        if self._persist_thread is not None:
            self._stop_persist.set()
            self._persist_thread.join(timeout=5)
        self.save_all()
        if self._store is not None:
            try:
                self._store.checkpoint_wal()
                self._store.close()
            except Exception as e:
                logger.error(f"Pool store close failed: {e}")
            finally:
                self._store = None


# Global instance
_pool_instance: Optional[OpportunityPool] = None
_pool_lock = threading.Lock()


def get_opportunity_pool(**kwargs) -> OpportunityPool:
    global _pool_instance
    with _pool_lock:
        if _pool_instance is None:
            _pool_instance = OpportunityPool(**kwargs)
        return _pool_instance


def reset_opportunity_pool():
    global _pool_instance
    with _pool_lock:
        if _pool_instance:
            _pool_instance.stop()
            _pool_instance = None